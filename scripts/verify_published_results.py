"""Check the compact report package, without claiming to rerun experiments.

Published summaries are deliberately not full resumable experiment directories.
Raw prediction archives and execution journals are regenerated by the independent
experiment commands. This checker never accepts a summary as a full run.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import re
import zipfile

import numpy as np

from scripts.verify_results import verify_figures, verify_files


# Each experiment's formal result directory name under results/formal; the checker
# only accepts a package whose published.json names one of these experiments.
EXPERIMENTS = {
    "M1": "M1_equation_identification", "M2": "M2_recursive_prediction",
    "M3": "M3_cross_resolution", "S1": "S1_high_frequency_branch",
    "S2": "S2_recursive_local_correction", "S3": "S3_seed_stability",
    "S4": "S4_initial_distribution",
}


def verify_field_source(path):
    """Allow bounded numeric figure arrays, not pickles or training datasets."""
    if path.name != "source_fields.npz" or path.stat().st_size > 50 * 1024**2:
        raise ValueError("Unexpected or oversized figure source archive")
    try:
        with zipfile.ZipFile(path) as compressed:
            entries = compressed.infolist()
            if (not entries or len(entries) > 1000
                    or sum(e.file_size for e in entries) > 64 * 1024**2
                    or any(not e.filename.endswith(".npy") for e in entries)):
                raise ValueError("Unexpected or oversized uncompressed figure source")
    except zipfile.BadZipFile as error:
        raise ValueError("Invalid figure source archive") from error
    with np.load(path, allow_pickle=False) as archive:
        if not archive.files or len(archive.files) != len(set(archive.files)):
            raise ValueError("Empty/duplicate figure array inventory")
        total = 0
        for key in archive.files:
            array = archive[key]
            if array.dtype.kind not in "biuf" or not np.isfinite(array).all():
                raise ValueError("Figure source must contain finite real numeric arrays")
            total += array.size
            if total > 2_000_000:
                raise ValueError("Figure source exceeds the selected-panel size budget")


def verify_package(root, experiment):
    """Verify every included byte and figure binding; omitted raw files stay omitted."""
    # A published package is scoped to summaries and selected figures only: it must
    # declare full_raw_outputs_included False and resumable_experiment False, so a
    # compact archive can never masquerade as a complete resumable run.
    root = Path(root).resolve(strict=True)
    manifest = json.loads((root / "published.json").read_text(encoding="utf-8"))
    if (manifest.get("schema") != "gift.published-results.v1"
            or manifest.get("experiment") != experiment
            or experiment not in EXPERIMENTS
            or manifest.get("scope") != "summaries_and_selected_figures"
            or manifest.get("full_raw_outputs_included") is not False
            or manifest.get("resumable_experiment") is not False):
        raise ValueError("Not an explicitly scoped published result package")
    measurement = manifest["measurement"]
    if not re.fullmatch(r"[A-Fa-f0-9]{64}", measurement.get("report_sha256", "")):
        raise ValueError("Missing source measurement report hash")
    files = verify_files(root, manifest["files"])
    if "summary/metrics.csv" not in files:
        raise ValueError("Published metrics are missing")
    actual = {p.relative_to(root).as_posix() for p in root.rglob("*") if p.is_file()}
    if actual != set(files) | {"published.json"}:
        raise ValueError("Published file inventory differs from directory contents")
    figure_dirs = manifest["figure_directories"]
    if not isinstance(figure_dirs, list) or len(figure_dirs) != len(set(figure_dirs)):
        raise ValueError("Invalid figure directory inventory")
    covered = set()
    checks = []
    field_archives = []
    for relative in figure_dirs:
        if (not isinstance(relative, str) or "\\" in relative or ":" in relative
                or any(p in ("", ".", "..") for p in relative.split("/"))
                or relative.split("/")[0] != "figures"):
            raise ValueError("Unsafe figure directory")
        directory = root / relative
        record_name = relative + "/figure_manifest.json"
        if record_name not in files:
            raise ValueError("Unbound figure manifest")
        checks.append(verify_figures(directory, {
            "experiment": experiment, "report_sha256": measurement["report_sha256"].upper()}))
        figure = json.loads((root / record_name).read_text(encoding="utf-8"))
        bound = {relative + "/" + r["path"] for r in figure["files"]} | {record_name}
        if not bound <= set(files) or covered & bound:
            raise ValueError("Missing or multiply owned figure file")
        covered |= bound
        for name in bound:
            if Path(name).suffix.lower() == ".npz":
                verify_field_source(root / name)
                field_archives.append(name)
    for name in files:
        if name in {"summary/metrics.csv", "summary/summary.json"}:
            continue
        if name not in covered or Path(name).suffix.lower() not in {".svg", ".csv", ".npz", ".json"}:
            raise ValueError("Unexpected file in compact published package: " + name)
    return dict(status="PASS_PUBLISHED_INTEGRITY_ONLY", experiment=experiment,
                files_verified=len(files), figure_checks=checks, figure_array_files=field_archives,
                full_raw_outputs_verified=False, numerical_metrics_recomputed=False,
                training_performed=False)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, allow_abbrev=False)
    parser.add_argument("--result-dir", type=Path, required=True)
    parser.add_argument("--experiment", choices=tuple(EXPERIMENTS), required=True)
    args = parser.parse_args(argv)
    print(json.dumps(verify_package(args.result_dir, args.experiment), indent=2))


if __name__ == "__main__":
    main()
